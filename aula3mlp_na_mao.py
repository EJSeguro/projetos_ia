class Layer:
  def __init__(self, n_inputs, n_neurons):
    #normalizando o random
    self.pesos = 0.1*np.random.randn(n_inputs, n_neurons)
    self.bias = np.zeros((1, n_neurons))
    #ajuste na chamada
  def forward(self, inputs, ativacao=None):
    self.output = np.dot(inputs, self.pesos,) + self.bias
    if ativacao == "relu":
      self.output = self.relu(self.output)
    elif ativacao == "softmax":
      self.output = self.softmax(self.output)
  def relu(self, inputs):
    return np.maximum(0, inputs)
  def softmax(self, inputs):
    saida = np.exp(inputs - np.max(inputs, axis=1, keepdims=True))
    saida_normalizada = saida / np.sum(saida, axis=1, keepdims=True)
    return saida_normalizada

